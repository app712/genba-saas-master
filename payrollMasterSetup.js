// 引数で渡されたシート名のシートを削除する。誤削除防止のため、削除対象は必ず listAllSheetNames() で
// 実際のシート名を確認してから明示的に指定すること（自動判定・一括削除はしない）。
function cleanupLegacySheets(sheetNamesToDelete) {
  const ss = SpreadsheetApp.openById(TEMPLATE_SS_ID);
  (sheetNamesToDelete || []).forEach(name => {
    const sheet = ss.getSheetByName(name);
    if (sheet) ss.deleteSheet(sheet);
  });
}


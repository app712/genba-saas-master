// 既存の社員マスタ（16列）に給与計算用の列を末尾追加する。既存列順は変更しない（列ズレ防止）。
// 複数回実行しても同じ列を重複追加しない（冪等）。
function extendEmployeeSheet(ss) {
  const sheet = ss.getSheetByName(SHEET_EMPLOYEES);
  if (!sheet) throw new Error("社員マスタが見つかりません");
  const lastCol = Math.max(1, sheet.getLastColumn());
  const existingHeaders = sheet.getRange(1, 1, 1, lastCol).getValues()[0].map(h => String(h).trim());
  let nextCol = lastCol + 1;
  EMPLOYEE_HEADERS_EXTRA.forEach(colName => {
    if (existingHeaders.indexOf(colName) === -1) {
      sheet.getRange(1, nextCol).setValue(colName).setBackground("#4a86e8").setFontColor("white").setFontWeight("bold");
      nextCol++;
    }
  });
}

